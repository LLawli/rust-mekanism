//! A ordem do `ObjectOpenHashSet`, do `Long2ObjectOpenHashMap` e do `removeIf` do fastutil 8.5.18 nos pontos que a rede de transmissores usa
//! e que `sim::open_hash` ainda não tinha: `addAll` e `putAll` (que reservam `size() + outro.size()` com `tryCapacity` antes de inserir),
//! `clear()` (que não encolhe a tabela) e `values().removeIf(...)`. As saídas esperadas são as do `Ref.java` rodado contra o jar real
//! (`fastutil-8.5.18.jar`, o do Minecraft 26.3), com o mesmo gerador congruencial de `open_hash.rs`.
use machinery_basis_core::sim::open_hash::{OpenHashMap, OpenHashSet, OpenKey, mix_int, mix_long};

/// O gerador do `Ref.java`: `state = state * 6364136223846793005 + 1442695040888963407`.
struct Lcg(i64);

impl Lcg {
    fn next(&mut self, bound: i64) -> i64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        (((self.0 as u64) >> 33) as i64) % bound
    }
}

/// O `K(id, hash)` do `Ref.java`: o `hashCode` é `id * 1103515245 + 12345` e a igualdade é pelo `id`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct K(i32);

impl OpenKey for K {
    fn mixed(self) -> i32 {
        mix_int(self.0.wrapping_mul(1_103_515_245).wrapping_add(12345))
    }
}

/// A chave `long` do `Long2ObjectOpenHashMap`: a `0` é a chave nula.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct L(i64);

impl OpenKey for L {
    fn mixed(self) -> i32 {
        mix_long(self.0)
    }

    const NULL_KEY: Option<Self> = Some(L(0));
}

fn ids(keys: &[K]) -> String {
    keys.iter()
        .map(|k| k.0.to_string())
        .collect::<Vec<_>>()
        .join(" ")
}

fn longs(keys: &[L]) -> String {
    keys.iter()
        .map(|k| k.0.to_string())
        .collect::<Vec<_>>()
        .join(" ")
}

