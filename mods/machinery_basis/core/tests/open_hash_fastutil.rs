#[test]
fn add_all_remove_and_clear_follow_fastutil() {
    let mut expected = SETS.iter();
    for seed in 1..=3 {
        let mut lcg = Lcg(seed * 11);
        let mut set = OpenHashSet::new();
        for round in 0..6 {
            let count = lcg.next(if round == 3 { 40 } else { 14 }) + 1;
            let batch: Vec<K> = (0..count).map(|_| K(lcg.next(60) as i32)).collect();
            if round % 3 == 2 {
                let mut source = OpenHashSet::new();
                source.add_all(&batch);
                set.add_all(&source.in_order());
            } else {
                set.add_all(&batch);
            }
            if round == 4 {
                for key in batch.iter().step_by(2) {
                    set.remove(*key);
                }
            }
            if round == 5 {
                set.clear();
                set.add_all(&batch[..batch.len().min(3)]);
            }
            assert_eq!(
                ids(&set.in_order()),
                *expected.next().unwrap(),
                "conjunto {seed}, rodada {round}"
            );
        }
    }
}

#[test]
fn put_all_and_clear_follow_fastutil() {
    let mut expected = MAPS.iter();
    for seed in 1..=3 {
        let mut lcg = Lcg(seed * 17);
        let mut map: OpenHashMap<L, ()> = OpenHashMap::new();
        for round in 0..5 {
            let mut other: OpenHashMap<L, ()> = OpenHashMap::new();
            let count = lcg.next(if round == 2 { 30 } else { 9 }) + 1;
            for _ in 0..count {
                other.insert(L(lcg.next(1 << 40) - (1 << 39)), ());
            }
            if round == 3 {
                for key in map.keys_in_order() {
                    if lcg.next(2) == 0 {
                        map.remove(key);
                    }
                }
            }
            map.put_all(other.entries_in_order().into_iter().map(|(k, v)| (k, *v)));
            assert_eq!(
                longs(&map.keys_in_order()),
                *expected.next().unwrap(),
                "mapa {seed}, rodada {round}"
            );
        }
        map.clear_keeping_table();
        for _ in 0..4 {
            map.insert(L(lcg.next(1 << 40)), ());
        }
        assert_eq!(
            longs(&map.keys_in_order()),
            *expected.next().unwrap(),
            "mapa {seed} depois de clear"
        );
    }
}

/// `values().removeIf` percorre a tabela tirando com `shiftKeys`; tirar as mesmas chaves uma a uma deixa a mesma ordem.
#[test]
fn remove_if_matches_removing_the_keys_one_by_one() {
    let mut expected = REMOVE_IF.iter();
    for seed in 1..=6 {
        let mut lcg = Lcg(seed * 23);
        let mut map: OpenHashMap<L, bool> = OpenHashMap::new();
        let count = 5 + lcg.next(60);
        for _ in 0..count {
            let a = lcg.next(1 << 30);
            let sign = if lcg.next(2) == 0 { 1 } else { -1 };
            let b = i64::from(lcg.next(3) != 0);
            let flag = lcg.next(3) == 0;
            map.insert(L(a * sign + b), flag);
        }
        let flagged: Vec<L> = map
            .entries_in_order()
            .into_iter()
            .filter(|(_, flag)| **flag)
            .map(|(key, _)| key)
            .collect();
        for key in flagged {
            map.remove(key);
        }
        assert_eq!(
            longs(&map.keys_in_order()),
            *expected.next().unwrap(),
            "removeIf {seed}"
        );
    }
}
